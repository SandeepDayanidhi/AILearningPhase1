#program to calculate the average marks of the students 
#marks of 3 subjects students as input in the form of float and then find out the average.

mark1 = float(input("enter first subject marks :"))
mark2 = float(input("enter second subject marks :"))
mark3 = float(input("enter third subject marks :"))

